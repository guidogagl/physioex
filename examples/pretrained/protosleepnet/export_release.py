"""Build the Hugging Face folder of a multi-dataset ProtoSleepNet / ProtoSleepTransformer checkpoint.

Takes a training checkpoint (``{model, cfg, backbone, step, epoch}``) and the per-site evaluation JSON of the same step
(``{step, epoch, ckpt, val, test}``, one entry per site) and writes the layout read by ``physioex.models.load_from_pretrained``::

    <out>/<name>/
      model.pt       state_dict only
      config.json    model_class + factory + factory_kwargs + training summary
      metrics.json   per-site test metrics (accuracy, f1_score, cohen_kappa, n_subjects)

Nothing is recomputed: every metric is copied from the evaluation JSON. Sites in ``--exclude`` were not training sites (dropped from
config.json and metrics.json); sites in ``--no_metrics`` were trained on but their metrics are not published. The aggregate ``_macro``
entry is always dropped (it averages over all sites, the excluded ones included).

    python export_release.py --ckpt seq_step00161500.pt --eval_json eval/step_00161500.json \\
        --splits splits_29sites.json --name protosleepnet-gagliardi --out hf_release --exclude ccshs \\
        --no_metrics alzheimers_hc parkinsons_night_hoa

Upload is a separate, explicit step (``huggingface_hub.HfApi.upload_folder``); this script never touches the network.
"""
import argparse
import hashlib
import json
from pathlib import Path

import torch

from physioex.models.protosleepnet import ProtoSleepNet

FACTORY = {"seq": "from_seq_sleep_net", "st": "from_sleep_transformer"}
MIXER_KWARGS = dict(n_channels=3, use_channel_mixer=True, cdropout=0.5, cm_n_heads=4, cm_d_ff=256, cm_n_layers=1)
REFERENCE = {
    "seq": "Gagliardi et al. - Prototype-based interpretable sleep staging with physiologically meaningful sub-stage pattern "
           "discovery (npj Digital Medicine); ProtoSleepNet with a SeqSleepNet epoch encoder",
    "st": "Gagliardi et al. - Prototype-based interpretable sleep staging with physiologically meaningful sub-stage pattern "
          "discovery (npj Digital Medicine); ProtoSleepNet with a SleepTransformer epoch encoder (ProtoSleepTransformer)",
}
TRAIN_KEYS = ("max_epochs", "epoch_size", "batch_size", "lr", "weight_decay", "cdropout", "scheduler", "seed", "val_subjects_per_site")
METRIC_MAP = (("accuracy", "accuracy"), ("f1", "f1_score"), ("kappa", "cohen_kappa"), ("n_subjects", "n_subjects"))


def sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def site_metrics(eval_json: dict, sites: list, hidden=()) -> dict:
    """Per-site test metrics in the ``metrics.json`` layout, without ``hidden`` sites; fails if the evaluation does not cover exactly ``sites``."""
    test = {k: v for k, v in eval_json["test"].items() if k != "_macro"}
    if set(test) != set(sites):
        raise ValueError(f"evaluation sites differ from the expected ones: "
                         f"only in eval {sorted(set(test) - set(sites))}, missing {sorted(set(sites) - set(test))}")
    return {s: {dst: test[s][src] for src, dst in METRIC_MAP} for s in sorted(sites) if s not in hidden}


def docs_table(name: str, metrics: dict) -> str:
    rows = ["| Site | Test subjects | Accuracy | Cohen's kappa | Macro F1 |", "|---|---:|---:|---:|---:|"]
    for s, m in metrics.items():
        rows.append(f"| `{s}` | {m['n_subjects']} | {m['accuracy']:.3f} | {m['cohen_kappa']:.3f} | {m['f1_score']:.3f} |")
    return f"<!-- {name}: generated by export_release.py from metrics.json -->\n" + "\n".join(rows) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--eval_json", required=True, help="per-site evaluation of the same step")
    ap.add_argument("--splits", required=True, help="splits JSON whose keys are the training sites")
    ap.add_argument("--name", required=True, help="folder name on the Hub, e.g. protosleepnet-gagliardi")
    ap.add_argument("--out", required=True)
    ap.add_argument("--exclude", nargs="*", default=[], help="not training sites: left out of config.json and metrics.json")
    ap.add_argument("--no_metrics", nargs="*", default=[], help="training sites whose metrics are not published (kept in config.json)")
    ap.add_argument("--docs_table", default=None, help="also write the per-site Markdown table used by the documentation page")
    a = ap.parse_args()

    ck = torch.load(a.ckpt, map_location="cpu", weights_only=True)
    ev = json.load(open(a.eval_json))
    backbone = ck["backbone"]
    if ev["step"] != ck["step"]:
        raise ValueError(f"evaluation is for step {ev['step']}, checkpoint is step {ck['step']}")
    sites = sorted(set(json.load(open(a.splits))) - set(a.exclude))
    metrics = site_metrics(ev, sites, set(a.no_metrics))

    model = getattr(ProtoSleepNet, FACTORY[backbone])(**MIXER_KWARGS)
    model.load_state_dict(ck["model"], strict=True)
    state = {k: v.detach().cpu().contiguous() for k, v in ck["model"].items()}

    out = Path(a.out) / a.name
    out.mkdir(parents=True, exist_ok=True)
    torch.save(state, out / "model.pt")
    cfg = ck["cfg"]
    config = {
        "model_class": "physioex.models.protosleepnet:ProtoSleepNet",
        "factory": FACTORY[backbone],
        "factory_kwargs": MIXER_KWARGS,
        "training": {
            "backbone": backbone,
            "dataset": "multi-dataset",
            "sites": sites,
            "channels": cfg["channels"],
            "pipeline_preset": cfg["pipeline"],
            "sequence_length": cfg["sequence_length"],
            "step": ck["step"],
            "epoch": ck["epoch"],
            **{k: cfg[k] for k in TRAIN_KEYS if k in cfg},
            "n_parameters": sum(p.numel() for p in model.parameters()),
            "model_pt_sha256": sha256(out / "model.pt"),
        },
        "reference": REFERENCE[backbone],
    }
    (out / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    if a.docs_table:
        Path(a.docs_table).write_text(docs_table(a.name, metrics))
    print(json.dumps({"name": a.name, "step": ck["step"], "sites": len(sites), "n_parameters": config["training"]["n_parameters"],
                      "ckpt_sha256": sha256(a.ckpt), "eval_sha256": sha256(a.eval_json),
                      "model_pt_sha256": config["training"]["model_pt_sha256"]}, indent=2))


if __name__ == "__main__":
    main()
